import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export function discoverBundled(root) {
  const directory = path.join(root, 'modules/Bundled');
  return fs.readdirSync(directory, { withFileTypes: true })
    .filter(entry => entry.isDirectory() && fs.existsSync(path.join(directory, entry.name, 'module.json')))
    .map(entry => ({ ...JSON.parse(fs.readFileSync(path.join(directory, entry.name, 'module.json'), 'utf8')), folder: entry.name }))
    .sort((a, b) => (a.compositionOrder ?? 100) - (b.compositionOrder ?? 100) || a.id.localeCompare(b.id, 'en'));
}

export function bundledBackend(modules, host) {
  if (host === 'TemplateV4.BackgroundWorker')
    return `// <auto-generated />\nnamespace TemplateV4.Infrastructure;\npublic static class BundledWorker\n{\n    public static void Register(Microsoft.Extensions.DependencyInjection.IServiceCollection services, Microsoft.Extensions.Configuration.IConfiguration configuration)\n    {\n${modules.filter(m => m.host.worker).map(m => `        ${m.host.worker}(services, configuration);`).join('\n')}\n    }\n}\n`;
  const infrastructure = host === 'TemplateV4.Composition';
  const body = infrastructure
    ? `public static void Register(Microsoft.Extensions.DependencyInjection.IServiceCollection services, Microsoft.Extensions.Configuration.IConfiguration configuration, Microsoft.Extensions.Hosting.IHostEnvironment environment)\n    {\n${modules.filter(m => m.host.services).map(m => `        ${m.host.services}(services, configuration);`).join('\n')}\n    }`
    : `public static void Configure(Microsoft.AspNetCore.Builder.WebApplicationBuilder builder)\n    {\n${modules.filter(m => m.host.configure).map(m => `        ${m.host.configure}(builder);`).join('\n')}\n    }\n    public static void Map(Microsoft.AspNetCore.Builder.WebApplication app)\n    {\n${modules.filter(m => m.host.map).map(m => `        ${m.host.map}(app);`).join('\n')}\n    }`;
  return `// <auto-generated />\nnamespace TemplateV4.Infrastructure;\npublic static class ${infrastructure ? 'BundledRegistration' : 'BundledHttp'}\n{\n    ${body}\n}\n`;
}

export function bundledFrontend(modules) {
  const features = modules.filter(m => m.host.feature);
  return `// Generated by tools/discover-bundled-modules.mjs. Do not edit.\nimport type { FoundationFeature } from './app/core/feature-extensions';\n${features.map((m, i) => `import { ${m.host.feature} as feature${i} } from '../../../modules/Bundled/${m.folder}/Frontend/public-api';`).join('\n')}\nexport const bundledFeatures: readonly FoundationFeature[] = [${features.map((_, i) => `feature${i}`).join(', ')}];\n`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const root = path.resolve(import.meta.dirname, '..');
  const modules = discoverBundled(root);
  const hostIndex = process.argv.indexOf('--host');
  const host = hostIndex < 0 ? null : process.argv[hostIndex + 1];
  if (host && !['TemplateV4.Composition', 'TemplateV4.Http', 'TemplateV4.BackgroundWorker'].includes(host)) throw new Error('Unknown bundled composition host.');
  const output = host ? process.argv[hostIndex + 2] : path.join(root, 'src/TemplateV4.Angular/src/bundled-modules.g.ts');
  const content = host ? bundledBackend(modules, host) : bundledFrontend(modules);
  fs.mkdirSync(path.dirname(output), { recursive: true });
  if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8') !== content) fs.writeFileSync(output, content);
}
