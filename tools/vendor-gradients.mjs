// Extract the rendering/data dependency closure from the pinned FeralUI bundle.
// Usage: node tools/vendor-gradients.mjs <downloaded JapaneseGradients bundle>
// Never execute the downloaded application; parse it and reject external dependencies.
import fs from "node:fs";
import path from "node:path";
import ts from "../src/TemplateV4.Angular/node_modules/typescript/lib/typescript.js";
import { pathToFileURL } from "node:url";
import * as prettier from "../src/TemplateV4.Angular/node_modules/prettier/index.mjs";

const input = path.resolve(process.argv[2]);
const program = ts.createProgram([input], {
  allowJs: true,
  noLib: true,
  noResolve: true,
});
const checker = program.getTypeChecker();
const source = program.getSourceFile(input);
const declarations = new Map();
for (const statement of source.statements) {
  if (ts.isVariableStatement(statement)) {
    for (const declaration of statement.declarationList.declarations)
      declarations.set(checker.getSymbolAtLocation(declaration.name), {
        node: declaration,
        kind:
          statement.declarationList.flags & ts.NodeFlags.Const
            ? "const"
            : "let",
      });
  } else if (ts.isFunctionDeclaration(statement) && statement.name) {
    declarations.set(checker.getSymbolAtLocation(statement.name), {
      node: statement,
    });
  }
}
const selected = new Set();
const visit = (node) => {
  if (ts.isIdentifier(node)) {
    const symbol = checker.getSymbolAtLocation(node);
    if (symbol?.declarations?.some((d) => ts.isImportSpecifier(d)))
      throw new Error(`External dependency: ${node.text}`);
    const entry = declarations.get(symbol);
    if (entry && !selected.has(entry)) {
      selected.add(entry);
      ts.forEachChild(entry.node, visit);
    }
  }
  ts.forEachChild(node, visit);
};
const roots = {
  _1: "paintGradient",
  _a: "presetsByType",
  ns: "typeNames",
  Ke: "defaultsByType",
  ao: "defaultBlur",
  ro: "defaultGrain",
  Fe: "initialTime",
  xl: "grainTile",
};
for (const name of Object.keys(roots)) {
  const entry = [...declarations.values()].find(
    (entry) => entry.node.name.getText(source) === name,
  );
  if (!entry) throw new Error(`Missing root ${name}`);
  visit(entry.node.name);
}
const body = [...selected]
  .sort((a, b) => a.node.pos - b.node.pos)
  .map(({ node, kind }) =>
    kind ? `${kind} ${node.getText(source)};` : node.getText(source),
  )
  .join("\n\n");
const output = path.resolve(
  "src/TemplateV4.Angular/src/app/shared/gradient-engine.js",
);
fs.writeFileSync(
  output,
  "// FeralUI Gradient Builder by Sarthak Navalekar. See THIRD-PARTY-NOTICES.md.\n// Rendering and preset data only; extracted with tools/vendor-gradients.mjs.\n" +
    body +
    "\nexport { " +
    Object.entries(roots)
      .map(([local, name]) => `${local} as ${name}`)
      .join(", ") +
    " };\n",
);
console.log(
  `Extracted ${selected.size} declarations (${body.length} characters).`,
);

const engine = await import(pathToFileURL(output));
const legacy = {
  "d-sky": "blue-sky",
  yp2: "madder-dusk",
  yp3: "golden-hour",
  yp4: "night-sky",
  yp5: "storm-light",
  yp6: "blossom-sky",
  yp7: "mint-sky",
  yp8: "coral-haze",
};
const speeds = {
  FLOW: 30,
  SKY: 22,
  AURORA: 26,
  SILK: 0,
  STRIPE: 26,
  RETRO: 22,
  BARS: 34,
  COLS: 34,
  PRISM2: 40,
  PIXEL: 30,
  GLASSY: 30,
  LINE: 0,
  GLOW: 0,
};
const types = Object.entries(engine.typeNames)
  .filter(([id]) => id !== "PRISM")
  .map(([id, name]) => ({ id, name, label: `gradientType${id}` }));
const presets = types.flatMap(({ id: type }) =>
  engine.presetsByType[type].map((p) => ({
    id:
      type === "SKY" && legacy[p.id]
        ? legacy[p.id]
        : `${type.toLowerCase()}:${p.id}`,
    sourceId: p.id,
    type,
    name: p.e ?? p.name ?? p.id,
    label: `gradientPreset_${type}_${p.id}`,
    stops: p.stops,
    speed: type in speeds ? (p.speed ?? speeds[type]) : 0,
  })),
);
if (
  presets.some((p) => p.id.length > 32) ||
  new Set(presets.map((p) => p.id)).size !== presets.length
)
  throw new Error("Invalid persisted IDs");
fs.writeFileSync(
  "src/TemplateV4.Angular/src/app/core/gradient-catalog.ts",
  "// Generated by tools/vendor-gradients.mjs. Preset names are upstream artwork titles.\nexport const GRADIENT_CATALOG = " +
    JSON.stringify({ types, presets }, null, 2) +
    ";\n",
);
fs.writeFileSync(
  "src/TemplateV4.Application/Platform/LoginBackgroundCatalog.cs",
  "// Generated by tools/vendor-gradients.mjs.\nnamespace TemplateV4.Application.Platform;\n\ninternal static class LoginBackgroundCatalog\n{\n    internal static readonly HashSet<string> Ids =\n    [\n" +
    presets.map((p) => `        "${p.id}",`).join("\n") +
    "\n    ];\n}\n",
);
console.log(
  `${types.length} types, ${presets.length} presets; existing Sky IDs preserved.`,
);
for (const file of [
  output,
  "src/TemplateV4.Angular/src/app/core/gradient-catalog.ts",
]) {
  const options = await prettier.resolveConfig(file);
  fs.writeFileSync(
    file,
    await prettier.format(fs.readFileSync(file, "utf8"), {
      ...options,
      filepath: file,
    }),
  );
}
